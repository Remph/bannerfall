-- 1.5 push notifications (01-architecture §4.8b): the devices that get Web Push for a player, and
-- the kinds he switched away from their default. Gone with the player (never deleted while the
-- world runs); the server deletes a device itself on logout, when its sessions end, or when its
-- push service says it is gone.
create table push_subscription (
    id           bigint        generated by default as identity primary key,
    player_id    bigint        not null references player (id) on delete cascade,
    -- the push service's address for this browser; unique, so a browser that logs in as somebody
    -- else moves to him
    endpoint     varchar(1000) not null unique,
    p256dh       varchar(100)  not null,               -- the browser's public key, base64url
    auth         varchar(50)   not null,               -- its auth secret, base64url
    language     varchar(2)    not null,               -- the device's game language: en, de
    created_at   timestamptz   not null,
    last_sent_at timestamptz                           -- the last push the service accepted
);
create index push_subscription_player on push_subscription (player_id);

create table push_preference (
    player_id bigint      not null references player (id) on delete cascade,
    kind      varchar(20) not null,                    -- PushKind
    enabled   boolean     not null,
    primary key (player_id, kind)
);
