-- M3: the world (one settings row), players, villages and unit stacks.
-- Settings: docs/plan/02-game-rules.md §1. Tables: docs/plan/03-data-model.md.

create table world_settings (
    id                        smallint         primary key check (id = 1),
    name                      varchar(64)      not null,
    speed                     double precision not null,
    unit_speed                double precision not null,
    map_size                  int              not null,
    start_resources           int              not null,
    luck_range                double precision not null,
    beginner_protection_hours int              not null,
    noble_max_distance        int              not null,
    loyalty_regen_per_hour    double precision not null,
    build_queue_size          int              not null,
    recruit_queue_size        int              not null,
    cancel_window_seconds     int              not null,
    barbarian_initial_count   int              not null,
    barbarians_per_new_player int              not null,
    barbarian_growth_enabled  boolean          not null,
    trade_max_ratio           double precision not null,
    invite_code               varchar(64)      not null,
    started_at                timestamptz      not null
);

