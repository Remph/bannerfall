create table player (
    id              bigint generated by default as identity primary key,
    account_id      bigint      null references account (id), -- null for NPC lords
    name            varchar(24) not null,
    npc             boolean     not null default false,
    points          int         not null default 0,
    village_count   int         not null default 0,
    protected_until timestamptz not null,
    created_at      timestamptz not null,
    version         bigint      not null default 0,
    constraint player_account_id_uq unique (account_id),
    constraint player_name_uq unique (name)
);

create table village (
    id                   bigint generated by default as identity primary key,
    player_id            bigint           null references player (id), -- null = barbarian
    name                 varchar(32)      null,                         -- null for barbarians
    x                    int              not null,
    y                    int              not null,
    wood                 double precision not null,
    clay                 double precision not null,
    iron                 double precision not null,
    resources_updated_at timestamptz      not null,
    loyalty              double precision not null default 100,
    loyalty_updated_at   timestamptz      not null,
    points               int              not null default 0,
    -- building levels, enum order of BuildingType (02-game-rules §4.1)
    b_headquarters       smallint         not null default 0,
    b_barracks           smallint         not null default 0,
    b_stable             smallint         not null default 0,
    b_workshop           smallint         not null default 0,
    b_academy            smallint         not null default 0,
    b_smithy             smallint         not null default 0,
    b_rally_point        smallint         not null default 0,
    b_market             smallint         not null default 0,
    b_woodcutter         smallint         not null default 0,
    b_clay_pit           smallint         not null default 0,
    b_iron_mine          smallint         not null default 0,
    b_farm               smallint         not null default 0,
    b_warehouse          smallint         not null default 0,
    b_hiding_place       smallint         not null default 0,
    b_wall               smallint         not null default 0,
    created_at           timestamptz      not null,
    version              bigint           not null default 0,
    constraint village_xy_uq unique (x, y)
);

create index village_player_id_idx on village (player_id);

-- Units standing somewhere. home = location is the village's own army at home.
create table unit_stack (
    id                  bigint generated by default as identity primary key,
    home_village_id     bigint not null references village (id),
    location_village_id bigint not null references village (id),
    -- unit counts, enum order of UnitType (02-game-rules §5.1)
    u_spearman          int    not null default 0,
    u_swordsman         int    not null default 0,
    u_axeman            int    not null default 0,
    u_scout             int    not null default 0,
    u_light_cavalry     int    not null default 0,
    u_heavy_cavalry     int    not null default 0,
    u_ram               int    not null default 0,
    u_catapult          int    not null default 0,
    u_noble             int    not null default 0,
    version             bigint not null default 0,
    constraint unit_stack_home_location_uq unique (home_village_id, location_village_id)
);

create index unit_stack_location_village_id_idx on unit_stack (location_village_id);
