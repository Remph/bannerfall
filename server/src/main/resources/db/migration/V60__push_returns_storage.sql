-- Push for returning attacks and full warehouses (1.6, 01-architecture §4.8b).

-- Attacks whose return the owner wants to hear about once: one manual attack, an attack train or a
-- farm list run. One push when the last of them is home (or died); the row goes with it.
create table return_watch (
    id                bigint      generated by default as identity primary key,
    player_id         bigint      not null references player (id) on delete cascade,
    village_id        bigint      not null references village (id) on delete cascade, -- home
    -- the one target of a single attack or a train; null for a farm list run
    target_village_id bigint      references village (id) on delete set null,
    farm_run          boolean     not null,
    attacks           integer     not null,  -- how many it waits for
    lost              integer     not null default 0,  -- attacks nobody came back from
    loot_wood         integer     not null default 0,  -- what came home so far
    loot_clay         integer     not null default 0,
    loot_iron         integer     not null default 0,
    created_at        timestamptz not null
);
create index return_watch_player on return_watch (player_id);

alter table movement add column return_watch_id bigint references return_watch (id) on delete set null;
create index movement_return_watch on movement (return_watch_id) where return_watch_id is not null;

-- Villages whose full warehouse was pushed to their owner: pushed again only after the row is gone,
-- which the storage check does once nothing is full any more.
create table storage_full_push (
    village_id bigint      primary key references village (id) on delete cascade,
    player_id  bigint      not null references player (id) on delete cascade,
    pushed_at  timestamptz not null
);
