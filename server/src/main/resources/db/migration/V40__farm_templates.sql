-- Farm templates (1.4): up to five per player, named A to E, shared by all his villages. A farm
-- list entry may use one; it keeps a copy of the template's units, which changes with the template
-- (under the locks of the player's villages), so sending an entry reads its own row as before.
-- Rules: docs/plan/02-game-rules.md §18.

create table farm_template (
    id              bigint generated by default as identity primary key,
    player_id       bigint      not null references player (id) on delete cascade,
    letter          varchar(1)   not null check (letter in ('A', 'B', 'C', 'D', 'E')),
    u_spearman      int         not null,
    u_swordsman     int         not null,
    u_axeman        int         not null,
    u_scout         int         not null,
    u_light_cavalry int         not null,
    u_heavy_cavalry int         not null,
    u_ram           int         not null,
    u_catapult      int         not null,
    u_noble         int         not null,
    u_paladin       int         not null,
    u_banner_thief  int         not null,
    unique (player_id, letter)
);

-- A deleted template leaves its entries with the units they had ("own troops").
alter table farm_target
    add column template_id bigint null references farm_template (id) on delete set null;

create index farm_target_template on farm_target (template_id);
