-- M4: the event engine (game_event) and the building queue (build_order, used from M4b).
-- Tables: docs/plan/03-data-model.md. Event rules: docs/plan/01-architecture.md §4.6.

create table game_event (
    id           bigint generated by default as identity primary key, -- tie-breaker for equal due_at
    kind         varchar(32) not null,                                -- GameEventKind
    ref_id       bigint      null,                                    -- build_order, movement ...; no FK (polymorphic)
    due_at       timestamptz not null,
    status       varchar(16) not null,                                -- PENDING / DONE / FAILED
    attempts     int         not null default 0,
    last_error   text        null,
    created_at   timestamptz not null,
    processed_at timestamptz null                                     -- when it became DONE or FAILED
);

-- What the event worker asks for: the next due events, in order.
create index game_event_due on game_event (due_at, id) where status = 'PENDING';

-- What reschedule/cancel ask for: the pending events of one thing (e.g. one build order).
create index game_event_pending_ref on game_event (kind, ref_id) where status = 'PENDING';

create table build_order (
    id               bigint generated by default as identity primary key,
    village_id       bigint      not null references village (id) on delete cascade,
    building         varchar(32) not null,  -- BuildingType
    target_level     smallint    not null,  -- for display; completion does level + 1
    duration_seconds int         not null,  -- kept so the queue can be re-timed after a cancel
    start_at         timestamptz not null,
    end_at           timestamptz not null,
    cost_wood        int         not null,  -- the costs are kept for refunds
    cost_clay        int         not null,
    cost_iron        int         not null,
    cost_pop         int         not null,
    created_at       timestamptz not null
);

create index build_order_village_end_idx on build_order (village_id, end_at);
