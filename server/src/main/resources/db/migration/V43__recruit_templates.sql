-- Recruit templates (1.4): up to five per player, named A to E with a short name of their own,
-- shared by all his villages. A template is the army a village should have (a goal); the recruit
-- page recruits what is missing. Only the web reads them, every order is checked as usual.
-- Rules: docs/plan/02-game-rules.md §5.2b.

create table recruit_template (
    id              bigint generated by default as identity primary key,
    player_id       bigint      not null references player (id) on delete cascade,
    letter          varchar(1)  not null check (letter in ('A', 'B', 'C', 'D', 'E')),
    name            varchar(16) not null,
    u_spearman      int         not null,
    u_swordsman     int         not null,
    u_axeman        int         not null,
    u_scout         int         not null,
    u_light_cavalry int         not null,
    u_heavy_cavalry int         not null,
    u_ram           int         not null,
    u_catapult      int         not null,
    u_noble         int         not null,
    u_paladin       int         not null,
    u_banner_thief  int         not null,
    unique (player_id, letter)
);
