-- v1.3: trading with the market itself (docs/plan/02-game-rules.md §12.1, 03-data-model.md).

-- What one unit of another resource costs; 0 = no trading with the market in this world.
alter table world_settings add column market_exchange_ratio double precision not null default 1.5;

-- One row per trade with the market. The daily cap sums receive_amount since the last midnight;
-- rows from before the current day are deleted when the village trades again.
create table market_exchange (
    id               bigint generated by default as identity primary key,
    village_id       bigint      not null references village (id) on delete cascade,
    give_resource    varchar(8)  not null,                    -- WOOD / CLAY / IRON
    give_amount      int         not null check (give_amount > 0),
    receive_resource varchar(8)  not null,
    receive_amount   int         not null check (receive_amount > 0),
    exchanged_at     timestamptz not null
);

create index market_exchange_village_id_idx on market_exchange (village_id, exchanged_at);
