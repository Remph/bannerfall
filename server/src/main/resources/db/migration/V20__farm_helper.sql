-- The farm helper: a list of targets per village, each with the units it is usually hit with.
-- Rules: docs/plan/02-game-rules.md §18. A list belongs to its village: it is dropped when the
-- village changes hands (village/OwnerChange), and a target that disappears takes its entry along.

create table farm_target (
    id                bigint generated by default as identity primary key,
    village_id        bigint      not null references village (id) on delete cascade,
    target_village_id bigint      not null references village (id) on delete cascade,
    u_spearman        int         not null,
    u_swordsman       int         not null,
    u_axeman          int         not null,
    u_scout           int         not null,
    u_light_cavalry   int         not null,
    u_heavy_cavalry   int         not null,
    u_ram             int         not null,
    u_catapult        int         not null,
    u_noble           int         not null,
    created_at        timestamptz not null,
    last_sent_at      timestamptz null,
    unique (village_id, target_village_id)
);

create index farm_target_target on farm_target (target_village_id);
