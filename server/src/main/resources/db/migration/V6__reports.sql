-- M8: reports, one row per recipient. Table: docs/plan/03-data-model.md. Rules: docs/plan/02-game-rules.md §14.
-- The payload is a ReportPayload record (BattleReport, SupportReport, ...) as JSON, with its "type".

create table report (
    id          bigint generated by default as identity primary key,
    player_id   bigint      not null references player (id) on delete cascade, -- the recipient
    kind        varchar(32) not null,                    -- ReportKind: ATTACK / DEFENSE / SCOUT / SUPPORT_ARRIVED / ...
    happened_at timestamptz not null,                    -- game time of the event, not when it was processed
    read        boolean     not null default false,
    payload     jsonb       not null,
    created_at  timestamptz not null
);

-- A player's reports, newest first (list, unread count).
create index report_player_happened_idx on report (player_id, happened_at desc, id desc);
