-- Village automation (1.6): from a player's third village on (world setting automation_villages,
-- 0 = off), a village works through a build plan by itself and, from a line in the plan on, keeps
-- one of the player's recruit templates filled. Rules: docs/plan/02-game-rules.md §25.

alter table world_settings add column automation_villages integer not null default 3
    check (automation_villages between 0 and 100);

-- Build plans A to E per player, shared by all their villages: an ordered list of lines, each
-- {"building": "WOODCUTTER", "level": 5} or the recruit line {"recruit": "B"} (at most one).
create table build_plan (
    id        bigint generated by default as identity primary key,
    player_id bigint      not null references player (id) on delete cascade,
    letter    varchar(1)  not null check (letter in ('A', 'B', 'C', 'D', 'E')),
    name      varchar(16) not null,
    lines     jsonb       not null,
    unique (player_id, letter)
);

-- The plan a village works through. Dropped when the village changes owner. paused_by_cancel: the
-- owner cancelled an order the automation had placed, so it stopped until the owner switches it on again.
create table village_automation (
    village_id       bigint     primary key references village (id) on delete cascade,
    plan_letter      varchar(1) not null check (plan_letter in ('A', 'B', 'C', 'D', 'E')),
    enabled          boolean    not null,
    paused_by_cancel boolean    not null default false
);

-- Orders the automation placed (a gear in the queue; it keeps at most two of its own).
alter table build_order add column automated boolean not null default false;
