-- M32a: banners (docs/plan/02-game-rules.md §21). The Banner Hall is a new building, a banner is
-- owned by a player and either lies in his stash or is equipped in one village. Two world settings:
-- banners on (default on) and a factor for the drop chances of the battle milestones (M32b).
alter table world_settings add column banners_enabled boolean not null default true;
alter table world_settings add column banner_drop_factor double precision not null default 1.0;

alter table village add column b_banner_hall smallint not null default 0;

create table banner (
    id                  bigint generated by default as identity primary key,
    owner_id            bigint      not null references player (id) on delete cascade,
    type                varchar(16) not null,            -- BannerType
    tier                smallint    not null check (tier between 1 and 3),
    -- the village it flies in, null = in the owner's stash; at most one banner per village
    equipped_village_id bigint unique references village (id) on delete set null,
    equipped_at         timestamptz,
    origin              varchar(16) not null,            -- FOUND / FUSED / GRANTED
    created_at          timestamptz not null
);

create index banner_owner_idx on banner (owner_id);

-- What happened to a banner. No foreign key on banner_id: the log outlives a destroyed banner.
create table banner_event (
    id             bigint generated by default as identity primary key,
    banner_id      bigint      not null,
    kind           varchar(16) not null,                 -- BannerEventKind
    from_player_id bigint references player (id) on delete set null,
    to_player_id   bigint references player (id) on delete set null,
    village_id     bigint references village (id) on delete set null,
    happened_at    timestamptz not null,
    detail         varchar(200)
);

create index banner_event_banner_idx on banner_event (banner_id, id);
create index banner_event_kind_idx on banner_event (kind, happened_at);
