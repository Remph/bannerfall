-- M5: recruitment (recruit_order). Table: docs/plan/03-data-model.md. Rules: docs/plan/02-game-rules.md §5.2.
-- No events: the village catch-up moves finished units into the home stack (01-architecture §4.4).

create table recruit_order (
    id               bigint generated by default as identity primary key,
    village_id       bigint      not null references village (id) on delete cascade,
    building         varchar(32) not null,           -- BuildingType: BARRACKS / STABLE / WORKSHOP / ACADEMY
    unit             varchar(32) not null,           -- UnitType
    count            int         not null,           -- units ordered
    completed_count  int         not null default 0, -- already moved into the home stack
    seconds_per_unit int         not null,           -- fixed at enqueue (building level of that moment)
    start_at         timestamptz not null,
    end_at           timestamptz not null,           -- start_at + count × seconds_per_unit
    unit_cost_wood   int         not null,           -- per unit, kept for refunds
    unit_cost_clay   int         not null,
    unit_cost_iron   int         not null,
    unit_pop         int         not null,
    created_at       timestamptz not null
);

-- One queue per building and village, in running order.
create index recruit_order_village_building_end_idx on recruit_order (village_id, building, end_at);
