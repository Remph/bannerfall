-- M30: unit levels (docs/plan/02-game-rules.md §5.4). The world setting is off by default, so a
-- running world stays as it is: every unit is level 1 and the smithy only shows the unit stats.
alter table world_settings add column unit_levels_enabled boolean not null default false;

-- The research of a player's unit levels. A row is one research step: the unit reaches `level` at
-- `end_at`. The level of a unit at time t is the highest `level` of its rows with end_at <= t (1
-- without one), so nothing has to be applied when a research is done: no event, no catch-up, and a
-- battle reads the levels of the moment it happens. Finished rows stay (at most two per unit and
-- player); a cancelled research is deleted. A village that changes owner loses its research that is
-- still running (without refund), the finished ones belong to the player.
create table research_order (
    id         bigint generated by default as identity primary key,
    player_id  bigint      not null references player (id) on delete cascade,
    village_id bigint      not null references village (id) on delete cascade, -- where it was started
    unit       varchar(32) not null,           -- UnitType
    level      int         not null,           -- the level the unit reaches (2 or 3)
    start_at   timestamptz not null,
    end_at     timestamptz not null,
    cost_wood  int         not null,           -- kept for the refund of a cancel
    cost_clay  int         not null,
    cost_iron  int         not null,
    created_at timestamptz not null,
    unique (player_id, unit, level)
);

create index research_order_village_idx on research_order (village_id, end_at);
