-- Dismissing units. Rules: docs/plan/02-game-rules.md §5.2a (decided in §15). Table: docs/plan/03-data-model.md.
-- Units leave the home stack when the order is placed; the order only counts them down, one by one, so
-- there are no events: the village catch-up deletes finished orders (01-architecture §4.4).

create table dismiss_order (
    id               bigint generated by default as identity primary key,
    village_id       bigint      not null references village (id) on delete cascade,
    building         varchar(32) not null,           -- BuildingType that recruits the unit: its dismiss queue
    unit             varchar(32) not null,           -- UnitType
    count            int         not null,           -- units to dismiss
    completed_count  int         not null default 0, -- already dismissed (population freed)
    seconds_per_unit int         not null,           -- fixed at enqueue: a fifth of the recruit time
    start_at         timestamptz not null,
    end_at           timestamptz not null,           -- start_at + count × seconds_per_unit
    created_at       timestamptz not null
);

-- One queue per building and village, in running order.
create index dismiss_order_village_building_end_idx on dismiss_order (village_id, building, end_at);
