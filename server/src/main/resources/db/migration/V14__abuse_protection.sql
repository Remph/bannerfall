-- M14e: abuse protection (docs/plan/01-architecture.md §4.12, 08-host-console §2).

-- Bans by the host (or the automatic lock): no login while banned_until lies ahead; 9999-12-31 is
-- "permanent". The reason is shown to the player on the login page.
alter table account add column banned_until timestamptz null;
alter table account add column ban_reason varchar(200) null;

-- Raised whenever the account's open sessions must end: ban, password reset, own password change.
-- A session remembers the value of its login; a session with an older one is ended at its next
-- request (AccountGuardFilter).
alter table account add column session_version int not null default 0;

-- The suspicion log: requests the web client never sends in normal play (foreign ids, invalid
-- input, rate-limit hits, CSRF failures, refused STOMP frames). Kept 30 days.
create table abuse_event (
    id         bigint generated by default as identity primary key,
    account_id bigint       not null references account (id),
    kind       varchar(32)  not null, -- AbuseKind
    endpoint   varchar(200) not null, -- e.g. "POST /api/villages/12/build-orders"
    detail     varchar(500) not null,
    at         timestamptz  not null
);

-- Per account, newest first (the suspicious list, the automatic lock's window).
create index abuse_event_account_at_idx on abuse_event (account_id, at desc);
-- The nightly cleanup.
create index abuse_event_at_idx on abuse_event (at);
