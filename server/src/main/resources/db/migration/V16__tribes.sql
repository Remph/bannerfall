-- Membership lives in its own table, not on `player`: joining and leaving must not touch the
-- player row, whose @Version the points updates of the event worker race on.

-- Off by default: the host switches tribes on (admin page / world-settings) before or after the
-- opening. Existing tribes stay readable when it is switched off again.
alter table world_settings add column tribes_enabled boolean not null default false;
alter table world_settings add column tribe_max_members int not null default 10;

create table tribe (
    id          bigint generated by default as identity primary key,
    name        varchar(30)  not null,                  -- 3-30 characters, see TribeText
    tag         varchar(5)   not null,                  -- 2-5 letters or digits, shown in brackets
    description varchar(500) not null default '',
    created_at  timestamptz  not null
);
-- Names and tags are unique ignoring case ("Wolves" and "wolves" are the same tribe).
create unique index tribe_name_lower on tribe (lower(name));
create unique index tribe_tag_lower  on tribe (lower(tag));

create table tribe_member (
    player_id bigint      primary key references player (id) on delete cascade, -- one tribe per player
    tribe_id  bigint      not null references tribe (id) on delete cascade,
    role      varchar(10) not null,                     -- LEADER or MEMBER
    joined_at timestamptz not null
);
create index tribe_member_tribe on tribe_member (tribe_id);
-- Exactly one leader per tribe at most. A hand-over demotes the old leader first.
create unique index tribe_member_one_leader on tribe_member (tribe_id) where role = 'LEADER';

create table tribe_invitation (
    id         bigint generated by default as identity primary key,
    tribe_id   bigint      not null references tribe (id) on delete cascade,
    player_id  bigint      not null references player (id) on delete cascade, -- the invited player
    invited_by bigint      not null references player (id) on delete cascade,
    created_at timestamptz not null,
    unique (tribe_id, player_id)
);
create index tribe_invitation_player on tribe_invitation (player_id);
