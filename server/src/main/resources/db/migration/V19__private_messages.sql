-- Private messages and the block list. Rules: docs/plan/02-game-rules.md §17.
-- A message belongs to two players; a player who is deleted takes his messages with him.

create table private_message (
    id           bigint generated by default as identity primary key,
    sender_id    bigint      not null references player (id) on delete cascade,
    recipient_id bigint      not null references player (id) on delete cascade,
    text         text        not null,
    created_at   timestamptz not null,
    -- null = unread. A message from a player the recipient has blocked is stored as read.
    read_at      timestamptz null
);

-- A conversation, read from either side, newest first.
create index private_message_pair on private_message (recipient_id, sender_id, id);
create index private_message_sent on private_message (sender_id, recipient_id, id);
-- The unread counter in the navigation.
create index private_message_unread on private_message (recipient_id) where read_at is null;

create table player_block (
    blocker_id bigint      not null references player (id) on delete cascade,
    blocked_id bigint      not null references player (id) on delete cascade,
    created_at timestamptz not null,
    primary key (blocker_id, blocked_id)
);

create index player_block_blocked on player_block (blocked_id);
