-- M7: troops on the way (movement). Table: docs/plan/03-data-model.md. Rules: docs/plan/02-game-rules.md §6.
-- Each movement has one MOVEMENT_ARRIVE event (game_event.ref_id = movement.id); the row is deleted when it arrives.

create table movement (
    id                bigint generated by default as identity primary key,
    kind              varchar(16) not null,                    -- ATTACK / SUPPORT / RETURN
    home_village_id   bigint      not null references village (id), -- the units' home (= source for ATTACK/SUPPORT, = target for RETURN)
    source_village_id bigint      not null references village (id), -- where the movement started
    target_village_id bigint      not null references village (id), -- where it arrives
    owner_player_id   bigint      not null references player (id),  -- for queries and permissions
    -- unit counts, enum order of UnitType (02-game-rules §5.1)
    u_spearman        int         not null,
    u_swordsman       int         not null,
    u_axeman          int         not null,
    u_scout           int         not null,
    u_light_cavalry   int         not null,
    u_heavy_cavalry   int         not null,
    u_ram             int         not null,
    u_catapult        int         not null,
    u_noble           int         not null,
    catapult_target   varchar(32),                             -- BuildingType; ATTACK with catapults only
    loot_wood         int         not null default 0,          -- RETURN only
    loot_clay         int         not null default 0,
    loot_iron         int         not null default 0,
    depart_at         timestamptz not null,
    arrive_at         timestamptz not null,
    created_at        timestamptz not null
);

-- Incoming list and the incoming-attacks count of a village.
create index movement_target_arrive_idx on movement (target_village_id, arrive_at);
-- All units of a village (population) and its outgoing list.
create index movement_home_village_id_idx on movement (home_village_id);
create index movement_source_village_id_idx on movement (source_village_id);
