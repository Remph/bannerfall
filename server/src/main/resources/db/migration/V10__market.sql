-- An open offer: "give offer_amount of offer_resource for want_amount of want_resource,
-- remaining_count times". Its resources were paid when it was created; its merchants are reserved
-- (remaining_count × ceil(offer_amount / 1000)) until it is accepted or cancelled.
create table trade_offer (
    id              bigint generated by default as identity primary key,
    village_id      bigint      not null references village (id) on delete cascade,
    offer_resource  varchar(8)  not null,                      -- WOOD / CLAY / IRON
    offer_amount    int         not null check (offer_amount > 0),
    want_resource   varchar(8)  not null,
    want_amount     int         not null check (want_amount > 0),
    remaining_count int         not null check (remaining_count > 0),
    created_at      timestamptz not null,
    version         bigint      not null default 0
);

create index trade_offer_village_id_idx on trade_offer (village_id);

-- Merchants on the way. One TRADE_ARRIVE event per transport (game_event.ref_id = id); the row
-- stays after the arrival (arrived = true) until the merchants are back (return_at), because the
-- busy merchants are counted from it. The nightly cleanup deletes it after that.
create table trade_transport (
    id                bigint generated by default as identity primary key,
    source_village_id bigint      not null references village (id),
    target_village_id bigint      not null references village (id),
    wood              int         not null,
    clay              int         not null,
    iron              int         not null,
    merchants         int         not null,
    depart_at         timestamptz not null,
    arrive_at         timestamptz not null,
    return_at         timestamptz not null,
    arrived           boolean     not null default false,
    created_at        timestamptz not null
);

-- Busy merchants and the outgoing list of a village.
create index trade_transport_source_return_idx on trade_transport (source_village_id, return_at);
-- The incoming list of a village.
create index trade_transport_target_arrive_idx on trade_transport (target_village_id, arrive_at);
