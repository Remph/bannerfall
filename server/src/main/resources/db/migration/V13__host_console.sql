-- M14d: the host console (docs/plan/08-host-console.md).

-- Audit log of every admin action (08 §6): who did what to which object. Players never see it.
create table admin_action (
    id          bigint generated by default as identity primary key,
    at          timestamptz not null,
    actor       varchar(64) not null,  -- the admin's username, or 'host-cli' for the host token
    action      varchar(64) not null,  -- e.g. RESET_PASSWORD, CHEAT_RESOURCES
    target_type varchar(32) null,      -- player, village, event, chat, world ...
    target_id   bigint      null,
    details     jsonb       not null default '{}'
);
-- The audit list pages newest first.
create index admin_action_at_idx on admin_action (at desc, id desc);

-- The players list shows when someone last logged in.
alter table account add column last_login_at timestamptz null;

-- A broadcast by the host is a chat message without an author.
alter table chat_message alter column player_id drop not null;
