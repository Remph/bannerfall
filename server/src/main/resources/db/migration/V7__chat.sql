-- The history pages by id (newest first, `id < before`), so the primary key is all the index it needs.

create table chat_message (
    id         bigint generated by default as identity primary key,
    player_id  bigint       not null references player (id) on delete cascade, -- the author
    text       varchar(500) not null,                   -- trimmed, 1-500 characters
    deleted    boolean      not null default false,     -- hidden by the admin (M14a)
    created_at timestamptz  not null
);
